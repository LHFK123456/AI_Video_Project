/** 全角字符（中日文）统一按 1em */
export const CJK_W = 1;

/** 未知字符兜底：取小写字母平均值 */
export const FALLBACK_W = 0.521;

/** 是否全角字符 */
export const isCJKChar = (ch: string): boolean => {
  const cp = ch.codePointAt(0) ?? 0;
  return (
    (cp >= 0x3000 && cp <= 0x30ff) ||
    (cp >= 0x3400 && cp <= 0x9fff) ||
    (cp >= 0xff00 && cp <= 0xffef)
  );
};

/** 单字符宽度（em） */
export const glyphWidth = (ch: string): number =>
  isCJKChar(ch) ? CJK_W : (GLYPH_W[ch] ?? FALLBACK_W);

/**
 * 合成粗体的宽度放大系数（实测值，不是经验值）。
 *
 * 上面那张字宽表是在 **weight 400** 下测出来的，但爆发期渲染用 **weight 600**。
 * Windows 的中文字体家族里没有真正的 600 字重，浏览器只能做"合成粗体"
 * （把笔画横向加粗），字宽因此变大 —— 拉丁字符 +6.2%，CJK 几乎不变（+0.3%，
 * 因为汉字本身就是满格字身，加粗只改变笔画不改变字身）。
 *
 * 这就是"蓄力期不溢出、爆发期溢出"的根因：同一句歌词在两段用了不同字重，
 * 却共用一份 400 字重测出的宽度。
 *
 * 重新测量：node scripts/measure-weights.mjs
 * 排版一律按**更宽的那个字重（600）**规划，这样蓄力期略有余量、爆发期刚好不溢出，
 * 全片又能保持同一套字号阶梯 —— 而不是为了不溢出把爆发期字号降一档。
 */
export const WEIGHT_SCALE = {
  /** 蓄力期：weight 300~400，基准 */
  regular: 1,
  /** 爆发期：weight 600，拉丁变宽、CJK 几乎不变 */
  semiboldLatin: 1.062,
  semiboldCJK: 1.003,
} as const;

/**
 * 整串宽度（em），不含字距。
 * @param bold 是否按爆发期（weight 600）的合成粗体计入宽度
 */
export const textWidth = (s: string, bold = false): number => {
  let w = 0;
  for (const ch of s) {
    if (bold) {
      w += glyphWidth(ch) * (isCJKChar(ch) ? WEIGHT_SCALE.semiboldCJK : WEIGHT_SCALE.semiboldLatin);
    } else {
      w += glyphWidth(ch);
    }
  }
  return w;
};
